import {describe, expect, it} from "vitest";
import {
    CARD_PREVIEW_ROW_CAP,
    addChild,
    blankComposition,
    capPreviewRows,
    deleteNode,
    duplicateNode,
    durationChipColor,
    formatHue,
    paintComposition,
    parseComposition,
    reportFormatterContext,
    sheetsFromReportJson,
    statusChipColor,
} from "./reportPreview.js";

describe("reportFormatterContext", () => {
    it("maps definition fields, Parameters.key, and Parameter_key", () => {
        const context = reportFormatterContext({Name: "Monthly", Id: "d1"}, [{key: "Region", value: "east"}]);
        expect(context.Name).toBe("Monthly");
        expect(context.Definition).toMatchObject({Name: "Monthly"});
        expect(context.Parameters).toEqual({Region: "east"});
        expect(context.Parameter_Region).toBe("east");
    });
});

describe("sheetsFromReportJson", () => {
    it("turns report JSON into sheets and caps card preview at 200 rows", () => {
        const json = JSON.stringify({
            sections: [
                {
                    tables: [
                        {
                            title: "Sales",
                            columns: [{header: "Name"}],
                            rows: [{cells: ["Ada"]}, {cells: ["Bea"]}],
                        },
                    ],
                },
            ],
        });
        const sheets = sheetsFromReportJson(json);
        expect(sheets).toEqual([{title: "Sales", headers: ["Name"], rows: [["Ada"], ["Bea"]]}]);
        const long = Array.from({length: 250}, (_, index) => String(index));
        expect(capPreviewRows(long)).toHaveLength(CARD_PREVIEW_ROW_CAP);
        expect(capPreviewRows(long)[0]).toBe("0");
    });
});

describe("composition edits", () => {
    it("adds, duplicates, and deletes a text block without removing the report", () => {
        const root = blankComposition("Draft");
        const sectionId = root.children[0]!.id;
        const before = root.children[0]!.children.filter((child) => child.kind === "block").length;
        const added = addChild(root, sectionId, "block");
        const section = added.children[0]!;
        const block = section.children[section.children.length - 1]!;
        expect(block.kind).toBe("block");
        expect(section.children.filter((child) => child.kind === "block")).toHaveLength(before + 1);
        const copied = duplicateNode(added, block.id);
        expect(copied.children[0]!.children.filter((child) => child.kind === "block")).toHaveLength(before + 2);
        const removed = deleteNode(copied, block.id);
        expect(removed.id).toBe(root.id);
        expect(removed.children[0]!.children.filter((child) => child.id === block.id)).toHaveLength(0);
    });
});

describe("paintComposition", () => {
    it("paints a blank composition as a titled page with one section and its text", () => {
        const paint = paintComposition(blankComposition("Draft"));
        expect(paint).toMatchObject({
            kind: "report",
            title: "Draft",
            subtitle: "Designed in the report workbench",
            footer: "Generated by Lyo Reporting",
            empty: false,
            dimmed: false,
        });
        expect(paint.children).toHaveLength(1);
        const section = paint.children[0]!;
        expect(section).toMatchObject({kind: "section", id: "summary", title: "Summary", depth: 0, empty: false});
        expect(section.children).toHaveLength(1);
        expect(section.children[0]).toMatchObject({kind: "block", id: "intro", content: "Replace this text."});
    });

    it("paints table headers and cell text", () => {
        const root = parseComposition(
            JSON.stringify({
                title: "Sales",
                sections: [
                    {
                        id: "sales",
                        title: "Sales",
                        controls: [
                            {
                                kind: "table",
                                id: "sales-table",
                                title: "Lines",
                                columns: [{header: "Name"}, {header: "Amount"}],
                                rows: [{cells: ["Ada", "10"]}],
                            },
                        ],
                    },
                ],
            })
        );
        expect(paintComposition(root).children[0]?.children[0]).toMatchObject({
            kind: "table",
            title: "Lines",
            headers: ["Name", "Amount"],
            rows: [["Ada", "10"]],
        });
    });

    it("paints a card label and value", () => {
        const root = parseComposition(
            JSON.stringify({
                title: "Dash",
                sections: [
                    {
                        id: "kpis",
                        title: "KPIs",
                        controls: [{kind: "card", id: "revenue", label: "Revenue", value: "120"}],
                    },
                ],
            })
        );
        expect(paintComposition(root).children[0]?.children[0]).toMatchObject({
            kind: "card",
            label: "Revenue",
            value: "120",
        });
    });

    it("fills {Region} in a text block from example parameters", () => {
        const root = parseComposition(
            JSON.stringify({
                title: "Regional",
                sections: [
                    {
                        id: "body",
                        title: "Body",
                        controls: [{kind: "block", id: "copy", contentType: "Text", content: "Region is {Region}."}],
                    },
                ],
            })
        );
        expect(paintComposition(root, [{key: "Region", value: "east"}]).children[0]?.children[0]).toMatchObject({
            kind: "block",
            content: "Region is east.",
        });
    });

    it("marks visibleWhen and collapsed nodes dimmed", () => {
        const root = parseComposition(
            JSON.stringify({
                title: "Hidden",
                sections: [
                    {id: "when", title: "When", visibleWhen: "Show", controls: []},
                    {id: "folded", title: "Folded", collapsed: true, controls: []},
                ],
            })
        );
        const paint = paintComposition(root);
        expect(paint.children[0]?.dimmed).toBe(true);
        expect(paint.children[1]?.dimmed).toBe(true);
        expect(paint.dimmed).toBe(false);
    });
});

describe("chip hues", () => {
    it("maps status, format, and duration the way the Blazor helper does", () => {
        expect(statusChipColor("succeeded")).toBe("success");
        expect(statusChipColor("failed")).toBe("error");
        expect(statusChipColor("running")).toBe("info");
        expect(statusChipColor("pending")).toBe("warning");
        expect(formatHue("pdf")).toBe("Rose");
        expect(formatHue("csv")).toBe("Teal");
        expect(formatHue("xlsx")).toBe("Lime");
        expect(formatHue("html")).toBe("Blue");
        expect(formatHue("json")).toBe("Violet");
        expect(durationChipColor(500)).toBe("success");
        expect(durationChipColor(40_000)).toBe("error");
    });
});
