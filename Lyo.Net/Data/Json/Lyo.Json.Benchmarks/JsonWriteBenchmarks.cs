using BenchmarkDotNet.Attributes;
using Lyo.Benchmark;
using Lyo.Benchmark.Data;
using Lyo.Common.Core.Identifiers;

namespace Lyo.Json.Benchmarks;

/// <summary>Times JSON serialization across bytes, string, stream, file, async, a pre-sized span, and NDJSON.</summary>
[BenchmarkDescription(
    "Serializes RowCount SampleRecords to JSON across the same write surfaces as CSV: bytes, string, stream, file, and the async byte path, plus a pre-sized span and NDJSON.")]
[BenchmarkParameter("RowCount", Unit = "rows", Description = "Number of SampleRecord rows serialized (100 to 100,000).")]
[BenchmarkDataShape(typeof(SampleRecord), Notes = "Flat 7-column record generated by SampleRecord.Generate. NDJSON is one compact object per line.")]
[BenchmarkSla(MaxMeanMs = 500, Standard = "Serializing up to 100k JSON records should complete within a few hundred milliseconds on the byte path.")]
public class JsonWriteBenchmarks
{
    private readonly JsonService _json = JsonService.Default;
    private byte[] _destination = null!;
    private string _filePath = null!;
    private List<SampleRecord> _rows = null!;

    [Params(100, 1_000, 10_000, 100_000)]
    public int RowCount { get; set; }

    [GlobalSetup]
    public void Setup()
    {
        _rows = SampleRecord.Generate(RowCount);
        _destination = new byte[_json.ExportToJsonBytes(_rows).Length];
        _filePath = Path.Combine(Path.GetTempPath(), $"lyo-json-write-{LyoGuid.CreateV7():N}.json");
    }

    [GlobalCleanup]
    public void Cleanup()
    {
        if (File.Exists(_filePath))
            File.Delete(_filePath);
    }

    [Benchmark(Baseline = true)]
    [BenchmarkDescription("Serialize the typed record list straight to UTF-8 JSON bytes (baseline).")]
    public byte[] ExportBytes() => _json.ExportToJsonBytes(_rows);

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list to a JSON string (extra UTF-16 materialization vs bytes).")]
    public string ExportString() => _json.ExportToJsonString(_rows);

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list into a MemoryStream.")]
    public long ExportStream()
    {
        using var stream = new MemoryStream();
        _json.ExportToJson(_rows, stream);
        return stream.Length;
    }

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list to a file on disk.")]
    public void ExportFile() => _json.ExportToJson(_rows, _filePath);

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list to JSON bytes via the async path.")]
    public async Task<byte[]> ExportBytesAsync() => await _json.ExportToJsonBytesAsync(_rows);

    [Benchmark]
    [BenchmarkDescription("Serialize the rows into a pre-sized UTF-8 span.")]
    public int TryExport()
    {
        _json.TryExport(_rows, _destination, out var written);
        return written;
    }

    [Benchmark]
    [BenchmarkDescription("Serialize the rows to UTF-8 NDJSON, one compact object per line.")]
    public byte[] ExportNdjson() => _json.ExportNdjsonBytes(_rows);
}