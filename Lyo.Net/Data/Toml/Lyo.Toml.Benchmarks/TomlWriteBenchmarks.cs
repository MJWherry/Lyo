using BenchmarkDotNet.Attributes;
using Lyo.Benchmark;
using Lyo.Benchmark.Data;
using Lyo.Common.Core.Identifiers;

namespace Lyo.Toml.Benchmarks;

/// <summary>Times TOML serialization across bytes, string, stream, file, async, and a pre-sized span.</summary>
[BenchmarkDescription(
    "Serializes RowCount SampleRecords to TOML across the same write surfaces as CSV: bytes, string, stream, file, and the async byte path, plus a pre-sized span.")]
[BenchmarkParameter("RowCount", Unit = "rows", Description = "Number of SampleRecord rows serialized (100 to 100,000).")]
[BenchmarkDataShape(typeof(SampleRecord), Notes = "Flat 7-column record generated by SampleRecord.Generate.")]
[BenchmarkSla(MaxMeanMs = 2000, Standard = "Serializing up to 100k TOML records should stay within a couple of seconds on the byte path.")]
public class TomlWriteBenchmarks
{
    private readonly TomlService _toml = TomlService.Default;
    private byte[] _destination = null!;
    private string _filePath = null!;
    private List<SampleRecord> _rows = null!;

    [Params(100, 1_000, 10_000, 100_000)]
    public int RowCount { get; set; }

    [GlobalSetup]
    public void Setup()
    {
        _rows = SampleRecord.Generate(RowCount);
        _destination = new byte[_toml.ExportToTomlBytes(_rows).Length];
        _filePath = Path.Combine(Path.GetTempPath(), $"lyo-toml-write-{LyoGuid.CreateV7():N}.toml");
    }

    [GlobalCleanup]
    public void Cleanup()
    {
        if (File.Exists(_filePath))
            File.Delete(_filePath);
    }

    [Benchmark(Baseline = true)]
    [BenchmarkDescription("Serialize the typed record list straight to UTF-8 TOML bytes (baseline).")]
    public byte[] ExportBytes() => _toml.ExportToTomlBytes(_rows);

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list to a TOML string (extra UTF-16 materialization vs bytes).")]
    public string ExportString() => _toml.ExportToTomlString(_rows);

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list into a MemoryStream.")]
    public long ExportStream()
    {
        using var stream = new MemoryStream();
        _toml.ExportToToml(_rows, stream);
        return stream.Length;
    }

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list to a file on disk.")]
    public void ExportFile() => _toml.ExportToToml(_rows, _filePath);

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list to TOML bytes via the async path.")]
    public async Task<byte[]> ExportBytesAsync() => await _toml.ExportToTomlBytesAsync(_rows);

    [Benchmark]
    [BenchmarkDescription("Serialize the rows into a pre-sized UTF-8 span.")]
    public int TryExport()
    {
        _toml.TryExport(_rows, _destination, out var written);
        return written;
    }
}