using System.Reflection;
using BenchmarkDotNet.Attributes;
using Lyo.Benchmark;

namespace Lyo.Csv.Benchmarks;

/// <summary>Benchmarks CSV serialization across destinations (bytes/string/stream/file), sync vs async, selected columns, and dynamic sources (DataTable, dictionary).</summary>
[BenchmarkDescription(
    "Serializes RowCount SampleRecords to CSV across every write surface: typed-list to bytes / string / stream / file, the async byte path, a selected-columns subset (3 of 7), and the dynamic DataTable and row/column-dictionary sources. Shows where extra materialization (UTF-16 string, file I/O, reflection vs dynamic columns) costs relative to the raw byte baseline.")]
[BenchmarkParameter("RowCount", Unit = "rows", Description = "Number of SampleRecord rows serialized (100 to 100,000).")]
[BenchmarkDataShape(
    typeof(SampleRecord),
    Notes = "Flat 7-column record generated by SampleRecord.Generate; sequential Id, formatted Name/Email, cycling Age/Balance/IsActive, and an incrementing CreatedAt.")]
[BenchmarkSla(
    MaxMeanMs = 500, Standard = "Serializing up to 100k typed rows to CSV should complete within a few hundred milliseconds (target >= 200k rows/sec on the hot byte path).")]
public class CsvWriteBenchmarks
{
    private readonly CsvService _csv = new();
    private DataTable.Models.DataTable _dataTable = null!;
    private IReadOnlyDictionary<int, IReadOnlyDictionary<int, string>> _dictionary = null!;
    private string _filePath = null!;
    private List<SampleRecord> _rows = null!;
    private IReadOnlyList<PropertyInfo> _selected = null!;

    [Params(100, 1_000, 10_000, 100_000)]
    public int RowCount { get; set; }

    [GlobalSetup]
    public void Setup()
    {
        _rows = SampleRecord.Generate(RowCount);
        var bytes = _csv.ExportToCsvBytes(_rows);
        _dataTable = _csv.ParseBytesAsDataTable(bytes).ValueOrThrow();
        _dictionary = _csv.ParseBytesAsDictionary(bytes);
        _selected = [
            typeof(SampleRecord).GetProperty(nameof(SampleRecord.Id))!, typeof(SampleRecord).GetProperty(nameof(SampleRecord.Name))!,
            typeof(SampleRecord).GetProperty(nameof(SampleRecord.Email))!
        ];

        _filePath = Path.Combine(Path.GetTempPath(), $"lyo-csv-write-{Guid.NewGuid():N}.csv");
    }

    [GlobalCleanup]
    public void Cleanup()
    {
        if (File.Exists(_filePath))
            File.Delete(_filePath);
    }

    [Benchmark(Baseline = true)]
    [BenchmarkDescription("Serialize the typed record list straight to UTF-8 CSV bytes (baseline).")]
    public byte[] ExportToCsvBytes() => _csv.ExportToCsvBytes(_rows);

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list to a CSV string (extra UTF-16 materialization vs bytes).")]
    public string ExportToCsvString() => _csv.ExportToCsvString(_rows);

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list into a MemoryStream (streamed writer, no intermediate string).")]
    public long ExportToCsvStream()
    {
        using var stream = new MemoryStream();
        _csv.ExportToCsvStream(_rows, stream);
        return stream.Length;
    }

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list to a file on disk (writer + filesystem I/O).")]
    public void ExportToCsvFile() => _csv.ExportToCsv(_rows, _filePath);

    [Benchmark]
    [BenchmarkDescription("Serialize the typed record list to CSV bytes via the async path.")]
    public async Task<byte[]> ExportToCsvBytesAsync() => await _csv.ExportToCsvBytesAsync(_rows);

    [Benchmark]
    [BenchmarkDescription("Serialize only 3 of the 7 columns (Id, Name, Email) to CSV bytes (selected-property reflection path).")]
    public byte[] ExportToCsvBytesSelected() => _csv.ExportToCsvBytes(_rows, _selected);

    [Benchmark]
    [BenchmarkDescription("Serialize a pre-parsed DataTable to CSV bytes (dynamic column path rather than typed reflection).")]
    public byte[] ExportToCsvBytesFromDataTable() => _csv.ExportToCsvBytesFromDataTable(_dataTable);

    [Benchmark]
    [BenchmarkDescription("Serialize a pre-built row/column dictionary map to CSV bytes (no typed model at all).")]
    public byte[] ExportToCsvBytesFromDictionary() => _csv.ExportToCsvBytesFromDictionary(_dictionary);
}